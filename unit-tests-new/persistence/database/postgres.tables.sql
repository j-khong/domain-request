-- postgres translation of tables.sql: same tables, columns, constraints and data
-- the names are lowercase snake_case, as postgres lowercases the unquoted identifiers (the sql aliases of the library)
-- the texts stay varchar (no citext): contains must stay case sensitive
-- the ids are never inserted explicitly, so the identity sequences need no setval
SET timezone = 'UTC';

DROP TABLE IF EXISTS course_applications CASCADE;
DROP TABLE IF EXISTS building_opening_hours CASCADE;
DROP TABLE IF EXISTS building_pictures CASCADE;
DROP TABLE IF EXISTS building_sponsors CASCADE;
DROP TABLE IF EXISTS students CASCADE;
DROP TABLE IF EXISTS student_categories CASCADE;
DROP TABLE IF EXISTS countries CASCADE;
DROP TABLE IF EXISTS buildings CASCADE;
DROP TABLE IF EXISTS building_categories CASCADE;
DROP TABLE IF EXISTS architects CASCADE;
DROP TABLE IF EXISTS ratings CASCADE;
DROP TABLE IF EXISTS raters CASCADE;
DROP TABLE IF EXISTS sponsors CASCADE;
DROP TABLE IF EXISTS courses CASCADE;
DROP TABLE IF EXISTS pictures CASCADE;

CREATE TABLE sponsors (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(255) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT sponsors__nk UNIQUE (name)
);

CREATE TABLE raters (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(255) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT raters__nk UNIQUE (name)
);

CREATE TABLE ratings (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  rate varchar(255) NOT NULL,
  id_rater integer NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT ratings__nk UNIQUE (rate, id_rater),
  CONSTRAINT ratings__fk_rater_id FOREIGN KEY (id_rater) REFERENCES raters (id)
);
CREATE INDEX ratings__idx_rater_id ON ratings (id_rater);

CREATE TABLE architects (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(255) NOT NULL,
  id_rating integer NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT architects__nk UNIQUE (name),
  CONSTRAINT architects__fk_rating_id FOREIGN KEY (id_rating) REFERENCES ratings (id)
);
CREATE INDEX architects__idx_rating_id ON architects (id_rating);

CREATE TABLE building_categories (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(255) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT building_categories__nk UNIQUE (name)
);

-- status: the enum('o','wip','c') of mysql
CREATE TABLE buildings (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(255) NOT NULL,
  status varchar(3) NOT NULL DEFAULT 'wip' CHECK (status IN ('o', 'wip', 'c')),
  confidential varchar(255) NOT NULL,
  id_category integer NOT NULL,
  id_architect integer NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT buildings__nk UNIQUE (name),
  CONSTRAINT buildings__fk_category_id FOREIGN KEY (id_category) REFERENCES building_categories (id),
  CONSTRAINT buildings__fk_architect_id FOREIGN KEY (id_architect) REFERENCES architects (id)
);
CREATE INDEX buildings__idx_category_id ON buildings (id_category);
CREATE INDEX buildings__idx_architect_id ON buildings (id_architect);

CREATE TABLE countries (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(255) NOT NULL,
  timezone varchar(255) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT countries__nk UNIQUE (name)
);

-- status: the enum('o','p','c','v') of mysql, seats_max: the smallint unsigned of mysql
CREATE TABLE courses (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(255) NOT NULL,
  published date NOT NULL,
  is_multilanguage boolean NOT NULL,
  status varchar(1) NOT NULL DEFAULT 'p' CHECK (status IN ('o', 'p', 'c', 'v')),
  seats_max integer NOT NULL CHECK (seats_max BETWEEN 0 AND 65535),
  PRIMARY KEY (id),
  CONSTRAINT courses__nk UNIQUE (name)
);

CREATE TABLE student_categories (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(255) NOT NULL,
  other_data varchar(255) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT student_categories__nk UNIQUE (name)
);

-- year_of_birth: the smallint unsigned of mysql
CREATE TABLE students (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  firstname varchar(255) NOT NULL,
  lastname varchar(255) NOT NULL,
  year_of_birth integer NOT NULL CHECK (year_of_birth BETWEEN 0 AND 65535),
  national_card_id varchar(255) NOT NULL,
  has_scholarship boolean NOT NULL,
  id_country integer NOT NULL,
  id_category integer NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT students__nk UNIQUE (national_card_id, id_country),
  CONSTRAINT students__fk_country_id FOREIGN KEY (id_country) REFERENCES countries (id),
  CONSTRAINT students__fk_category_id FOREIGN KEY (id_category) REFERENCES student_categories (id)
);
CREATE INDEX students__idx_country_id ON students (id_country);
CREATE INDEX students__idx_category_id ON students (id_category);

CREATE TABLE course_applications (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_student integer NOT NULL,
  id_course integer NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT course_applications__nk UNIQUE (id_student, id_course),
  CONSTRAINT id_course_applications__fk_student FOREIGN KEY (id_student) REFERENCES students (id),
  CONSTRAINT course_applications__fk_course_id FOREIGN KEY (id_course) REFERENCES courses (id)
);
CREATE INDEX id_course_applications__idx_student ON course_applications (id_student);
CREATE INDEX course_applications__idx_course_id ON course_applications (id_course);

-- "end" is a reserved word: it must be quoted when created, not when it is qualified by its table
CREATE TABLE building_opening_hours (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_building integer NOT NULL,
  day smallint NOT NULL,
  start varchar(5) NOT NULL,
  "end" varchar(5) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT building_opening_hours__fk_building_id FOREIGN KEY (id_building) REFERENCES buildings (id)
);
CREATE INDEX building_opening_hours__idx_building_id ON building_opening_hours (id_building);

CREATE TABLE building_sponsors (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_building integer NOT NULL,
  id_sponsor integer NOT NULL,
  contribution integer NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT building_sponsors__fk_building_id FOREIGN KEY (id_building) REFERENCES buildings (id),
  CONSTRAINT building_sponsors__fk_sponsor_id FOREIGN KEY (id_sponsor) REFERENCES sponsors (id)
);
CREATE INDEX building_sponsors__idx_building_id ON building_sponsors (id_building);
CREATE INDEX building_sponsors__idx_sponsor_id ON building_sponsors (id_sponsor);

CREATE TABLE pictures (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name varchar(20) NOT NULL,
  description varchar(200) NOT NULL,
  url varchar(200) NOT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE building_pictures (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_building integer NOT NULL,
  id_picture integer NOT NULL,
  status varchar(255) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT building_pictures__fk_building_id FOREIGN KEY (id_building) REFERENCES buildings (id),
  CONSTRAINT building_pictures__fk_picture_id FOREIGN KEY (id_picture) REFERENCES pictures (id)
);
CREATE INDEX building_pictures__idx_building_id ON building_pictures (id_building);
CREATE INDEX building_pictures__idx_picture_id ON building_pictures (id_picture);


